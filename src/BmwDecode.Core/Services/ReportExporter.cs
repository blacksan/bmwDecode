using System.Globalization;
using System.Net;
using System.Text;
using BmwDecode.Core.Catalog;

namespace BmwDecode.Core.Services;

/// <summary>Writes quick test reports as a self-contained HTML page or CSV.</summary>
public static class ReportExporter
{
    public static string ToHtml(QuickTestReport report)
    {
        static string E(string? s) => WebUtility.HtmlEncode(s ?? string.Empty);

        var v = report.Vehicle;
        var sb = new StringBuilder();
        sb.AppendLine("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">");
        sb.AppendLine($"<title>bmwDecode report {E(v.ShortVin ?? report.Series)}</title>");
        sb.AppendLine("""
            <style>
            body{font:14px/1.45 "Segoe UI Variable","Segoe UI",system-ui,sans-serif;margin:32px;color:#1b1b1b;background:#fafafa}
            h1{font-size:24px;margin:0 0 4px} h2{font-size:18px;margin:28px 0 8px}
            .muted{color:#616161} table{border-collapse:collapse;width:100%;background:#fff;border:1px solid #e5e5e5;border-radius:8px;overflow:hidden}
            th,td{padding:8px 10px;border-bottom:1px solid #eee;text-align:left;vertical-align:top} th{background:#f3f3f3;font-weight:600}
            .pill{display:inline-block;padding:2px 8px;border-radius:999px;font-size:12px;font-weight:600}
            .ok{background:#dff6dd;color:#0e700e}.bad{background:#fde7e9;color:#c42b1c}.na{background:#eee;color:#616161}.warn{background:#fff4ce;color:#8a5300}
            code{font-family:Consolas,"Cascadia Mono",monospace}
            dl{display:grid;grid-template-columns:max-content 1fr;gap:4px 16px;margin:0}
            dt{color:#616161}
            </style></head><body>
            """);
        sb.AppendLine($"<h1>Quick test – {E(SeriesNames.Describe(report.Series))}</h1>");
        sb.AppendLine($"<div class=\"muted\">{report.Started.ToString("f", CultureInfo.CurrentCulture)} · {report.Duration.TotalSeconds:0} s{(report.WasCancelled ? " · cancelled" : string.Empty)}</div>");

        sb.AppendLine("<h2>Vehicle</h2><dl>");
        sb.AppendLine($"<dt>VIN</dt><dd><code>{E(v.Vin ?? "not read")}</code></dd>");
        sb.AppendLine($"<dt>Series (detected)</dt><dd>{E(v.Series ?? "not read")}</dd>");
        sb.AppendLine($"<dt>Profile used</dt><dd>{E(report.Series)}</dd>");
        if (v.BatteryMillivolts is { } mv)
        {
            sb.AppendLine($"<dt>Battery</dt><dd>{mv / 1000.0:0.0} V</dd>");
        }

        sb.AppendLine($"<dt>Modules found</dt><dd>{report.Fitted.Count()}</dd>");
        sb.AppendLine($"<dt>Faults</dt><dd>{report.FaultCount}</dd></dl>");

        sb.AppendLine("<h2>Modules</h2><table><tr><th>Addr</th><th>Module</th><th>SGBD</th><th>Part no.</th><th>Status</th></tr>");
        foreach (var r in report.Results.Where(r => r.IsFitted).OrderBy(r => r.Ecu.Address))
        {
            var (cls, label) = r.State switch
            {
                EcuScanState.Faults => ("bad", $"{r.FaultList.Count} fault(s)"),
                EcuScanState.NoFaults => ("ok", "OK"),
                EcuScanState.Error => ("warn", "Error"),
                _ => ("na", r.State.ToString()),
            };
            sb.AppendLine($"<tr><td><code>{r.Ecu.AddressHex}</code></td><td><b>{E(r.Ecu.Abbreviation)}</b><br><span class=\"muted\">{E(r.Ecu.Description)}</span></td><td><code>{E(r.Variant)}</code></td><td>{E(r.PartNumber)}</td><td><span class=\"pill {cls}\">{E(label)}</span>{(r.Error is null ? string.Empty : $"<br><span class=\"muted\">{E(r.Error)}</span>")}</td></tr>");
        }

        sb.AppendLine("</table>");

        var withFaults = report.Results.Where(r => r.FaultList.Count > 0).ToList();
        if (withFaults.Count > 0)
        {
            sb.AppendLine("<h2>Fault memory</h2><table><tr><th>Module</th><th>Code</th><th>Description</th><th>Type</th><th>Present</th><th>Count</th></tr>");
            foreach (var r in withFaults)
            {
                foreach (var f in r.FaultList)
                {
                    var present = f.IsPresent switch { true => "<span class=\"pill bad\">Present</span>", false => "<span class=\"pill na\">Stored</span>", _ => string.Empty };
                    sb.AppendLine($"<tr><td>{E(r.Ecu.Abbreviation)}</td><td><code>{f.CodeHex}</code></td><td>{E(f.Text)}</td><td>{E(f.Symptom)}</td><td>{present}</td><td>{f.Frequency}</td></tr>");
                }
            }

            sb.AppendLine("</table>");
        }

        var missing = report.Results.Where(r => r.State == EcuScanState.NotFitted).Select(r => r.Ecu.Abbreviation);
        sb.AppendLine($"<h2>Not responding</h2><p class=\"muted\">{E(string.Join(", ", missing))}</p>");
        sb.AppendLine("<p class=\"muted\">Generated by bmwDecode.</p></body></html>");
        return sb.ToString();
    }

    public static string ToCsv(QuickTestReport report)
    {
        static string C(string? s)
        {
            s ??= string.Empty;
            return s.IndexOfAny([',', '"', '\n', '\r']) >= 0 ? "\"" + s.Replace("\"", "\"\"") + "\"" : s;
        }

        var sb = new StringBuilder();
        sb.AppendLine("address,module,description,sgbd,part_number,status,fault_code,fault_text,fault_type,present,count");
        foreach (var r in report.Results.OrderBy(r => r.Ecu.Address))
        {
            var head = $"{r.Ecu.AddressHex},{C(r.Ecu.Abbreviation)},{C(r.Ecu.Description)},{C(r.Variant)},{C(r.PartNumber)},{r.State}";
            if (r.FaultList.Count == 0)
            {
                sb.AppendLine(head + ",,,,,");
                continue;
            }

            foreach (var f in r.FaultList)
            {
                sb.AppendLine($"{head},{f.CodeHex},{C(f.Text)},{C(f.Symptom)},{f.IsPresent?.ToString() ?? string.Empty},{f.Frequency}");
            }
        }

        return sb.ToString();
    }
}
